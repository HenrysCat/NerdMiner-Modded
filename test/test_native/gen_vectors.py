#!/usr/bin/env python3
"""Writes vectors.h for test_main.cpp: stratum jobs and the block header the
miner must build from them, computed here independently with hashlib.

Header layout (what pools expect, see the stratum v1 docs):
  version  : the hex from mining.notify, byte-reversed (little-endian)
  prevhash : the stratum hex, each 4-byte word byte-reversed
  merkle   : sha256d(coinbase), then sha256d(merkle + branch) for each branch
  ntime, nbits : byte-reversed
  nonce    : 4 zero bytes (the miner fills it)
"""
import hashlib, os, random

def dsha(b):
    return hashlib.sha256(hashlib.sha256(b).digest()).digest()

def swap4(b):
    return b"".join(b[i:i + 4][::-1] for i in range(0, len(b), 4))

def header(job, en1, en2):
    cb = bytes.fromhex(job["coinb1"] + en1 + en2 + job["coinb2"])
    m = dsha(cb)
    for br in job["branches"]:
        m = dsha(m + bytes.fromhex(br))
    return (bytes.fromhex(job["version"])[::-1] + swap4(bytes.fromhex(job["prevhash"])) + m +
            bytes.fromhex(job["ntime"])[::-1] + bytes.fromhex(job["nbits"])[::-1] + b"\0" * 4)

rnd = random.Random(7)
def rhex(n):
    return bytes(rnd.getrandbits(8) for _ in range(n)).hex()

EN1 = "f8002c90"
JOBS = [
    # small coinbase, no merkle branch (an empty block)
    dict(name="empty", job_id="4f", prevhash=rhex(32), coinb1=rhex(42), coinb2=rhex(60), branches=[],
         version="20000000", nbits="17034219", ntime="6717a9b1"),
    # 300-byte coinbase (600 hex digits, more than the old 512-digit buffer) and 3 branches
    dict(name="big", job_id="a1b2", prevhash=rhex(32), coinb1=rhex(120), coinb2=rhex(172), branches=[rhex(32) for _ in range(3)],
         version="20000004", nbits="1702f128", ntime="6717aa00"),
]

# The two calls in test order: extranonce2 counts from 1 (calculateMiningData).
out = ["// GENERATED by test/test_native/gen_vectors.py -- do not edit by hand.", "#pragma once", ""]
for k, job in enumerate(JOBS):
    en2 = "%08x" % (k + 1)
    h = header(job, EN1, en2)
    n = job["name"]
    out.append('static const char *%s_notify = "{\\"id\\":null,\\"method\\":\\"mining.notify\\",\\"params\\":[\\"%s\\",\\"%s\\",\\"%s\\",\\"%s\\",[%s],\\"%s\\",\\"%s\\",\\"%s\\",true]}";' % (
        n, job["job_id"], job["prevhash"], job["coinb1"], job["coinb2"],
        ",".join('\\"%s\\"' % b for b in job["branches"]), job["version"], job["nbits"], job["ntime"]))
    out.append('static const char *%s_en2 = "%s";' % (n, en2))
    out.append("static const uint8_t %s_header[80] = {%s};" % (n, ",".join("0x%02x" % x for x in h)))
    out.append("")

# Block 125552 (the example of the Bitcoin wiki "Block hashing algorithm" page):
# a real header and its hash, for checkValid() and the SHA-256d code.
ver, prev, mrk = 1, "00000000000008a3a41b85b8b29ad444def299fee21793cd8b9e567eab02cd81", "2b12fcf1b09288fcaff797d71e950e71ae42b91e8bdb2304758dfcffc2b620e3"
t, bits, nonce = 1305998791, 0x1a44b9f2, 2504433986
hdr = (ver.to_bytes(4, "little") + bytes.fromhex(prev)[::-1] + bytes.fromhex(mrk)[::-1] +
       t.to_bytes(4, "little") + bits.to_bytes(4, "little") + nonce.to_bytes(4, "little"))
hh = dsha(hdr)
assert hh[::-1].hex() == "00000000000000001e8d6829a8a21adc5d38d0a473b144b6765798e61f98bd1d", hh[::-1].hex()
out.append("static const uint8_t block125552_header[80] = {%s};" % ",".join("0x%02x" % x for x in hdr))
out.append("static const uint8_t block125552_hash[32] = {%s}; // as the miner holds it: byte 31 most significant" % ",".join("0x%02x" % x for x in hh))
out.append('static const char *block125552_nbits = "1a44b9f2";')
out.append("")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.h"), "w").write("\n".join(out))
print("vectors.h written")
